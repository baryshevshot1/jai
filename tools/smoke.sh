#!/usr/bin/env bash
# ── Smoke-тест собранного бандла ──────────────────────────────────────────────
#
# Единственная проверка в проекте, которая имеет дело с ТЕМ САМЫМ бинарником, а не
# с исходниками. Все остальные отвечают на вопрос «что написано»; этот — на вопрос
# «что собралось». Разница между ними однажды стоила отладочной сессии: симптомы
# старого бандла сравнивались с симптомами нового как симптомы одного.
#
# Что делает: собирает приложение и запускает его с --self-check. Окно не
# открывается — приложение печатает JSON (версия, коммит, фичи, число команд,
# каталоги данных, состояние модели распознавания) и выходит.
#
# Чего НЕ делает и не может: проверить, что окно нарисовалось и интерфейс жив.
# Это закрывается только глазами — чек-лист в docs/RELEASE.md.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT"

# Homebrew в PATH нужен для cmake (whisper.cpp собирается из исходников).
export PATH="/opt/homebrew/bin:$PATH"

echo "── сборка бандла ──"
npx tauri build --bundles app >/tmp/jai-smoke-build.log 2>&1 || {
  # Отсутствие приватного ключа обновлений роняет ШАГ ПОДПИСИ, но сам бандл к тому
  # моменту уже собран. Разбираем этот случай отдельно, чтобы smoke не требовал
  # ключа: подпись проверяется при выпуске (tools/release.sh), а не здесь.
  if ! grep -q "private key" /tmp/jai-smoke-build.log; then
    tail -30 /tmp/jai-smoke-build.log
    echo "сборка бандла не удалась" >&2
    exit 1
  fi
  echo "   (шаг подписи обновления пропущен — нет TAURI_SIGNING_PRIVATE_KEY)"
}

case "$(uname -s)" in
  Darwin) BIN="src-tauri/target/release/bundle/macos/Jarvis AI.app/Contents/MacOS/jai" ;;
  Linux)  BIN="src-tauri/target/release/jai" ;;
  *)      echo "smoke-тест на этой системе не описан: $(uname -s)" >&2; exit 1 ;;
esac

if [ ! -x "$BIN" ]; then
  echo "бинарник не найден: $BIN" >&2
  exit 1
fi

echo "── самопроверка бинарника ──"
OUT="$("$BIN" --self-check)" || {
  echo "$OUT"
  echo "приложение сообщило о проблемах (--self-check вернул ненулевой код)" >&2
  exit 1
}
echo "$OUT"

# Разбираем результат: пустой список команд или отсутствие голоса в сборке по
# умолчанию — это отказ, а не мелочь. Grep, а не jq: лишняя зависимость в гейте,
# который должен работать на любой машине разработчика, того не стоит.
echo "$OUT" | grep -q '"ok": true' || { echo "самопроверка не «ok»" >&2; exit 1; }
echo "$OUT" | grep -q '"voice_built": true' \
  || { echo "бандл собран БЕЗ голосового ввода — это не релизная сборка" >&2; exit 1; }

echo "── бандл жив ──"
